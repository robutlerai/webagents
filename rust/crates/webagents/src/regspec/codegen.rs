//! Spec -> Rust source: the same table as `static` data (so firmware needs no
//! heap and no JSON parser for the spec), plus a typed API for people writing
//! firmware by hand: a value type per register with one getter and one `with_`
//! setter per field, an enum per mode field, and checked `write_*` methods that
//! go through the same envelope as the model's tools.
//!
//! Run it from `build.rs` (`webagents::regspec::codegen::generate`) or with the
//! `robutler-device regspec gen` command. The output depends only on the spec, so it
//! can be committed and reviewed like any source.

use std::fmt::Write;
use std::string::String;

use super::{Access, Bus, Device, Encoding, Field, Op, Operand, Register};

/// Rust source for `dev`, as a module named after the device.
pub fn generate(dev: &Device) -> String {
    let mut o = String::new();
    let m = dev.name;
    let w = &mut o;
    let _ = writeln!(w, "// Generated by webagents {} from the register spec of {} ({}). Do not edit; regenerate.", env!("CARGO_PKG_VERSION"), m, dev.title);
    let _ = writeln!(w, "#[allow(dead_code, unused_imports, non_camel_case_types, clippy::all)]");
    let _ = writeln!(w, "pub mod {} {{", ident(m));
    let _ = writeln!(w, "    use webagents::bus::RegisterBus;");
    let _ = writeln!(w, "    use webagents::regspec::{{Access, Bus, CallCtx, Cond, Dec, Device, Encoding, EnumValue, Field, FieldRef, Op, Operand, Register, Rule, ToolError}};");
    let _ = writeln!(w);
    let _ = writeln!(w, "    /// Fields across all registers; the size of the limit state.");
    let _ = writeln!(w, "    pub const FIELD_COUNT: usize = {};", dev.field_count);
    let _ = writeln!(
        w,
        "    pub static DEVICE: Device<'static> = Device {{ name: {:?}, title: {:?}, bus: {}, registers: &REGISTERS, field_count: FIELD_COUNT }};",
        dev.name,
        dev.title,
        bus(&dev.bus)
    );
    let _ = writeln!(w, "    static REGISTERS: [Register<'static>; {}] = [", dev.registers.len());
    for r in dev.registers {
        let _ = writeln!(
            w,
            "        Register {{ name: {:?}, desc: {:?}, offset: {:#x}, width: {}, access: {}, reset: {:#x}, read_side_effect: {}, first_field: {}, fields: &[",
            r.name,
            r.desc,
            r.offset,
            r.width,
            access(r.access),
            r.reset,
            r.read_side_effect,
            r.first_field
        );
        for f in r.fields {
            let _ = write!(
                w,
                "            Field {{ name: {:?}, desc: {:?}, lsb: {}, width: {}, access: {}, encoding: {}, scale: {:?}, offset: {:?}, unit: {:?}, min: {}, max: {}, confirm: {}, min_interval_ms: {}, enums: &[",
                f.name,
                f.desc,
                f.lsb,
                f.width,
                access(f.access),
                encoding(f.encoding),
                f.scale,
                f.offset,
                f.unit,
                f.min,
                f.max,
                f.confirm,
                f.min_interval_ms
            );
            for e in f.enums {
                let _ = write!(w, "EnumValue {{ name: {:?}, value: {}, desc: {:?} }}, ", e.name, e.value, e.desc);
            }
            let _ = write!(w, "], rules: &[");
            for rule in f.rules {
                let _ = write!(w, "Rule {{ when: ");
                match rule.when {
                    Some(c) => {
                        let _ = write!(w, "Some({})", cond(&c));
                    }
                    None => {
                        let _ = write!(w, "None");
                    }
                }
                let _ = write!(w, ", require: {}, why: {:?} }}, ", cond(&rule.require), rule.why);
            }
            let _ = writeln!(w, "] }},");
        }
        let _ = writeln!(w, "        ] }},");
    }
    let _ = writeln!(w, "    ];");
    let _ = writeln!(w);

    let _ = writeln!(w, "    /// Register offsets.");
    let _ = writeln!(w, "    pub mod offsets {{");
    for r in dev.registers {
        let _ = writeln!(w, "        pub const {}: u32 = {:#x};", ident(&r.name.to_ascii_uppercase()), r.offset);
    }
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w);

    for (ri, r) in dev.registers.iter().enumerate() {
        reg_type(w, ri, r);
    }

    let dt = camel(m);
    let _ = writeln!(w, "    /// The engine with a fixed-size limit state (no heap).");
    let _ = writeln!(w, "    pub type Engine<B> = webagents::regspec::Engine<'static, B, [u64; FIELD_COUNT]>;");
    let _ = writeln!(w);
    let _ = writeln!(w, "    /// Typed access to the {}. Reads go straight to the bus; writes go through the", dev.title);
    let _ = writeln!(w, "    /// same limits, rules and rate limits as the model's tools.");
    let _ = writeln!(w, "    pub struct {dt}<B> {{ pub engine: Engine<B> }}");
    let _ = writeln!(w, "    impl<B: RegisterBus> {dt}<B> {{");
    let _ = writeln!(w, "        pub fn new(bus: B) -> Self {{ {dt} {{ engine: Engine::new(&DEVICE, bus, [0; FIELD_COUNT]) }} }}");
    for (ri, r) in dev.registers.iter().enumerate() {
        let t = camel(r.name);
        let n = snake(r.name);
        if r.access.readable() {
            let _ = writeln!(w, "        /// Read {}.{}", r.name, if r.read_side_effect { " The read has a side effect." } else { "" });
            let _ =
                writeln!(w, "        pub fn read_{n}(&mut self) -> Result<{t}, B::Error> {{ self.engine.bus.read({:#x}, {}).map({t}) }}", r.offset, r.width);
        }
        if r.fields.iter().any(|f| f.access.writable()) {
            let _ = writeln!(w, "        /// Write {} after checking every writable field against its limits and rules.", r.name);
            let _ = writeln!(
                w,
                "        pub fn write_{n}(&mut self, v: {t}, ctx: &CallCtx) -> Result<(), ToolError<'static>> {{ self.engine.write_word({ri}, v.0, ctx) }}"
            );
            if r.access.readable() && !r.read_side_effect {
                let _ = writeln!(w, "        /// Read, change, and write {} (checked).", r.name);
                let _ = writeln!(
                    w,
                    "        pub fn modify_{n}(&mut self, ctx: &CallCtx, f: impl FnOnce({t}) -> {t}) -> Result<(), ToolError<'static>> {{ let v = self.engine.bus.read({:#x}, {}).map_err(|_| ToolError::Bus)?; self.engine.write_word({ri}, f({t}(v)).0, ctx) }}",
                    r.offset, r.width
                );
            }
        }
    }
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w, "}}");
    o
}

fn reg_type(w: &mut String, _ri: usize, r: &Register) {
    let t = camel(r.name);
    let _ = writeln!(w, "    /// {} ({}): {}", r.name, r.access.as_str(), one_line(r.desc));
    let _ = writeln!(w, "    #[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    let _ = writeln!(w, "    pub struct {t}(pub u32);");
    for f in r.fields.iter().filter(|f| !f.enums.is_empty()) {
        let et = format!("{t}{}", camel(f.name));
        let _ = writeln!(w, "    /// Values of {}.{}.", r.name, f.name);
        let _ = writeln!(w, "    #[derive(Clone, Copy, Debug, PartialEq, Eq)]");
        let _ = writeln!(w, "    #[repr(i64)]");
        let _ = writeln!(w, "    pub enum {et} {{");
        for e in f.enums {
            if !e.desc.is_empty() {
                let _ = writeln!(w, "        /// {}", one_line(e.desc));
            }
            let _ = writeln!(w, "        {} = {},", camel(e.name), e.value);
        }
        let _ = writeln!(w, "    }}");
    }
    let _ = writeln!(w, "    impl {t} {{");
    let _ = writeln!(w, "        pub const OFFSET: u32 = {:#x};", r.offset);
    let _ = writeln!(w, "        pub const RESET: Self = {t}({:#x});", r.reset);
    for f in r.fields {
        field_methods(w, &t, f);
    }
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w, "    impl Default for {t} {{ fn default() -> Self {{ Self::RESET }} }}");
    let _ = writeln!(w);
}

fn field_methods(w: &mut String, t: &str, f: &Field) {
    let n = snake(f.name);
    let mask = f.mask();
    let lsb = f.lsb;
    let wmask = if f.width >= 32 { u32::MAX } else { (1u32 << f.width) - 1 };
    let doc = one_line(f.desc);
    let unit = if f.unit.is_empty() { String::new() } else { format!(" ({})", f.unit) };
    match f.encoding {
        Encoding::Bool => {
            let _ = writeln!(w, "        /// {doc}");
            let _ = writeln!(w, "        pub const fn {n}(self) -> bool {{ (self.0 >> {lsb}) & 1 != 0 }}");
            let _ = writeln!(w, "        pub const fn with_{n}(self, v: bool) -> Self {{ Self((self.0 & !{mask:#x}) | ((v as u32) << {lsb})) }}");
        }
        Encoding::Unsigned => {
            let _ = writeln!(w, "        /// {doc} Count{}.", if f.is_scaled() { ", see the physical getter" } else { "" });
            let _ = writeln!(w, "        pub const fn {}(self) -> u32 {{ (self.0 >> {lsb}) & {wmask:#x} }}", count_name(f, &n));
            let _ = writeln!(
                w,
                "        pub const fn with_{}(self, v: u32) -> Self {{ Self((self.0 & !{mask:#x}) | ((v & {wmask:#x}) << {lsb})) }}",
                count_name(f, &n)
            );
        }
        Encoding::Signed => {
            let sh = 32 - f.width as u32;
            let _ = writeln!(w, "        /// {doc} Signed count.");
            let _ = writeln!(w, "        pub const fn {}(self) -> i32 {{ (((self.0 >> {lsb}) & {wmask:#x}) << {sh}) as i32 >> {sh} }}", count_name(f, &n));
            let _ = writeln!(
                w,
                "        pub const fn with_{}(self, v: i32) -> Self {{ Self((self.0 & !{mask:#x}) | (((v as u32) & {wmask:#x}) << {lsb})) }}",
                count_name(f, &n)
            );
        }
        Encoding::SignMagnitude => {
            let sign = 1u32 << (f.width - 1);
            let _ = writeln!(w, "        /// {doc} Sign-magnitude, as a signed count.");
            let _ = writeln!(w, "        pub const fn {}(self) -> i32 {{ let b = (self.0 >> {lsb}) & {wmask:#x}; let m = (b & {:#x}) as i32; if b & {sign:#x} != 0 {{ -m }} else {{ m }} }}", count_name(f, &n), sign - 1);
            let _ = writeln!(
                w,
                "        pub const fn with_{}(self, v: i32) -> Self {{ let b = if v < 0 {{ {sign:#x} | ((-v) as u32 & {:#x}) }} else {{ v as u32 & {:#x} }}; Self((self.0 & !{mask:#x}) | (b << {lsb})) }}",
                count_name(f, &n),
                sign - 1,
                sign - 1
            );
        }
    }
    if f.is_scaled() {
        let cn = count_name(f, &n);
        let _ = writeln!(w, "        /// {doc} In {}{unit}.", f.unit);
        let _ = writeln!(w, "        pub fn {n}(self) -> f64 {{ self.{cn}() as f64 * {} + {} }}", f64_lit(f.scale), f64_lit(f.offset));
    }
    if !f.enums.is_empty() {
        let et = format!("{t}{}", camel(f.name));
        let cn = count_name(f, &n);
        let _ = writeln!(w, "        /// {} as a named value, or `None` for a value the spec does not name.", f.name);
        let _ = writeln!(w, "        pub fn {n}_value(self) -> Option<{et}> {{ match self.{cn}() as i64 {{");
        for e in f.enums {
            let _ = writeln!(w, "            {} => Some({et}::{}),", e.value, camel(e.name));
        }
        let _ = writeln!(w, "            _ => None }} }}");
        let cast = if matches!(f.encoding, Encoding::Unsigned) { "u32" } else { "i32" };
        let _ = writeln!(w, "        pub fn with_{n}_value(self, v: {et}) -> Self {{ self.with_{cn}(v as i64 as {cast}) }}");
    }
}

/// The integer getter's name: the field name, or `<name>_count` when the field
/// also has a physical getter under its plain name.
fn count_name(f: &Field, n: &str) -> String {
    if f.is_scaled() {
        format!("{n}_count")
    } else {
        n.to_string()
    }
}

/// A `Dec` as an f64 literal for the typed getters (the engine itself never uses floats).
fn f64_lit(d: super::Dec) -> String {
    let t = d.to_string();
    if t.contains('.') {
        t
    } else {
        format!("{t}.0")
    }
}

fn bus(b: &Bus) -> String {
    match *b {
        Bus::Mmio { base } => format!("Bus::Mmio {{ base: {base:#x} }}"),
        Bus::I2c { address, addr_bytes, data_bytes, big_endian } => {
            format!("Bus::I2c {{ address: {address:#x}, addr_bytes: {addr_bytes}, data_bytes: {data_bytes}, big_endian: {big_endian} }}")
        }
        Bus::Spi { addr_bytes, data_bytes, big_endian } => {
            format!("Bus::Spi {{ addr_bytes: {addr_bytes}, data_bytes: {data_bytes}, big_endian: {big_endian} }}")
        }
        Bus::Custom => "Bus::Custom".into(),
    }
}

fn access(a: Access) -> &'static str {
    match a {
        Access::R => "Access::R",
        Access::RW => "Access::RW",
        Access::W => "Access::W",
        Access::W1 => "Access::W1",
    }
}

fn encoding(e: Encoding) -> &'static str {
    match e {
        Encoding::Unsigned => "Encoding::Unsigned",
        Encoding::Signed => "Encoding::Signed",
        Encoding::SignMagnitude => "Encoding::SignMagnitude",
        Encoding::Bool => "Encoding::Bool",
    }
}

fn operand(o: Operand) -> String {
    match o {
        Operand::New => "Operand::New".into(),
        Operand::Const(v) => format!("Operand::Const({v})"),
        Operand::Field(r) => format!("Operand::Field(FieldRef {{ reg: {}, field: {} }})", r.reg, r.field),
    }
}

fn op(o: Op) -> &'static str {
    match o {
        Op::Eq => "Op::Eq",
        Op::Ne => "Op::Ne",
        Op::Lt => "Op::Lt",
        Op::Le => "Op::Le",
        Op::Gt => "Op::Gt",
        Op::Ge => "Op::Ge",
    }
}

fn cond(c: &super::Cond) -> String {
    format!("Cond {{ lhs: {}, op: {}, rhs: {} }}", operand(c.lhs), op(c.op), operand(c.rhs))
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
    "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await",
    "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn ident(s: &str) -> String {
    let mut out: String = s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if out.chars().next().map_or(true, |c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

fn snake(s: &str) -> String {
    ident(&s.to_ascii_lowercase())
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    for part in s.split(|c: char| c == '_' || !c.is_ascii_alphanumeric()).filter(|p| !p.is_empty()) {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            out.extend(cs.map(|c| c.to_ascii_lowercase()));
        }
    }
    ident(&out)
}

